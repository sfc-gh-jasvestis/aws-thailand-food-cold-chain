FROM RAW.TEMPERATURE_READINGS f
JOIN RAW.THAI_FOOD_LOGISTICS e ON e.ID = f.ENTITY_ID
CROSS JOIN thresh
GROUP BY e.ID, e.NAME, e.REGION, e.CATEGORY, e.STATUS;

